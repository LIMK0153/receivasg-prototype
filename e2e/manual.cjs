// Manual-click paths (not the guided "Do it for me"): typed amounts, KYC, transfers, withdrawals.
const { chromium } = require("playwright");
const fs = require("fs"), path = require("path"), http = require("http");
const html = fs.readFileSync(path.join(__dirname, "..", "dist", "receivasg-prototype.html"), "utf8");
const server = http.createServer((q, r) => { r.writeHead(200, { "content-type": "text/html" }); r.end(html); }).listen(0);
const OUT = process.argv[2] || path.join(__dirname, "..", "e2e-shots");
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  p.on("pageerror", (e) => errors.push(e.message));
  await p.route(/fonts\./, (r) => r.abort());
  await p.goto(`http://127.0.0.1:${server.address().port}/`);
  await p.waitForSelector(".signin", { timeout: 60000 });
  await p.click("#signin-sme");
  const as = async (name) => { await p.click("#btn-account"); await p.locator(".acct-menu .acct-item", { hasText: name }).click(); };
  const nav = (label) => p.locator(".topnav button", { hasText: label }).click();
  const toast = async (label) => {
    await p.waitForSelector(".toasts .notice", { timeout: 20000 });
    await p.waitForTimeout(250);
    const t = (await p.locator(".toasts .notice").last().innerText()).replace(/\s+/g, " ").replace(" ×", "");
    console.log(`${label}: ${t}`);
    await p.evaluate(() => document.querySelectorAll(".toasts .x").forEach((x) => x.click()));
  };
  await as("Meridian"); await p.click("#btn-submit-INV-2026-0415"); await toast("SME submit 0415");
  await as("ReceivaSG Ops"); await p.click("#btn-verify"); await toast("Ops verify (model grade)");
  await as("Meridian"); await p.click("#btn-accept"); await toast("SME accept");
  await as("Lion Gate"); const card = p.locator(".offer-card", { hasText: "INV-2026-0415" });
  await card.locator("input").fill("10000"); console.log("validation shown:", await card.locator(".field-err").innerText().catch(() => "none"));
  await card.locator("input").fill("25000"); await card.locator("button.btn").click(); await toast("Lion Gate commits 25,000");
  await as("Harbourfront"); const card2 = p.locator(".offer-card", { hasText: "INV-2026-0415" });
  await card2.locator("button.chip", { hasText: "Fill remaining" }).click(); await card2.locator("button.btn").click(); await toast("Harbourfront fills");
  await as("Meridian"); console.log("SME balance:", await p.locator(".stat strong").first().innerText());
  await as("Unverified"); await nav("DDEx market");
  await p.locator("#btn-buy-0").click(); await toast("Unverified buys seeded listing");
  await as("ReceivaSG Ops"); await nav("Identity registry");
  await p.getByRole("button", { name: "Complete KYC" }).click(); await toast("Ops completes KYC");
  await as("Unverified"); await nav("DDEx market");
  await p.locator("#btn-buy-0").click(); await toast("Now-verified wallet buys listing");
  await as("Lion Gate"); await nav("Portfolio");
  await p.getByRole("button", { name: "Transfer" }).first().click();
  await p.selectOption("#xfer-to", "sme"); await p.locator(".transfer button.btn").click(); await toast("Transfer notes to SME");
  await p.getByRole("button", { name: "Withdraw" }).first().click(); await toast("Withdraw open commitment");
  await p.screenshot({ path: path.join(OUT, "30-portfolio.png") });
  await as("ReceivaSG Ops"); await nav("Platform book");
  await p.screenshot({ path: path.join(OUT, "31-book.png") });
  console.log(errors.length ? "ERRORS: " + errors.join(" | ") : "no page errors");
  await b.close(); server.close();
})().catch((e) => { console.error(e); server.close(); process.exit(1); });
